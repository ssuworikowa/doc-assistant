import json
from llm_client import ask_gigachat

def analyze_review_prompt(review_text: str) -> str:
    """
    Конструирует структурированный промпт с Few-shot примерами для анализа тональности.
    """
    prompt = f"""
Ты — профессиональный ИИ-аналитик маркетплейсов. Твоя задача — анализировать отзывы клиентов.
Определи тональность отзыва (positive, negative или neutral) и извлеки главный плюс и главный минус товара.

Выведи результат СТРОГО в формате JSON. Не пиши никаких вводных слов, markdown-разметки или пояснений. Только чистый JSON.

### ПРИМЕРЫ:
Входной отзыв: "Телефон просто супер, камера снимает отлично! Но батарея садится за полдня, очень жаль."
Выходной JSON:
{{"sentiment": "positive", "pros": "отличная камера", "cons": "слабая батарея"}}

Входной отзыв: "Доставка задержалась на три дня, коробка вся помятая. Сам товар вроде целый, но осадок остался."
Выходной JSON:
{{"sentiment": "negative", "pros": "товар без повреждений", "cons": "задержка доставки и помятая упаковка"}}

### РЕАЛЬНОЕ ЗАДАНИЕ:
Входной отзыв: "{review_text}"
Выходной JSON:
"""
    return prompt

if __name__ == "__main__":
    # Наш сырой отзыв для анализа
    user_review = """Купил эти наушники вчера. Звук чистый, объемный, за свои деньги топ. 
    Однако амбушюры слишком жесткие, уши начинают болеть через час использования."""
    
    print("1. Формируем сложный промпт...")
    final_prompt = analyze_review_prompt(user_review)
    
    print("2. Отправляем запрос в GigaChat...")
    raw_response = ask_gigachat(final_prompt, temperature=0.1) # Низкая температура для соблюдения структуры
    
    print(f"\nСырой ответ от модели:\n{raw_response}\n")
    
    print("3. Проверяем валидность полученного JSON...")
    try:
        parsed_json = json.loads(raw_response.strip())
        print("Успех! Данные успешно преобразованы в Python dict:")
        print(f"Тональность: {parsed_json.get('sentiment')}")
        print(f"Плюсы: {parsed_json.get('pros')}")
        print(f"Минусы: {parsed_json.get('cons')}")
    except json.JSONDecodeError:
        print("Ошибка: Модель нарушила формат и вернула невалидный JSON.")
